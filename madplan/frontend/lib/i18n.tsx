const dictionaries: Record<Locale, Record<TranslationKey, string>> = { da, en };

export type Translate = (key: TranslationKey, params?: Record<string, string | number | null | undefined>) => string;

interface I18n {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translate;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("da");
  const t = useCallback<Translate>(
    (key, params) => {
      let text = dictionaries[locale][key] ?? key;
      if (params) {
        for (const [name, value] of Object.entries(params)) {
          text = text.replaceAll(`{${name}}`, String(value ?? ""));
        }
      }
      return text;
    },
    [locale],
  );
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n outside I18nProvider");
  return context;
}

/** Turns a code from the API into a sentence, when there is one for it. */
export function errorText(t: Translate, error: unknown): string {
  const code = error instanceof Error ? error.message : "";
  if (code.startsWith("ai_unavailable:")) {
    const reason = code.split(":")[1];
    if (reason === "not_configured") return t("error.ai_not_configured");
    return t("error.ai_failed");
  }
  if (code.startsWith("allergy:")) return t("error.allergy", { item: code.split(":")[1] });
  const key = `error.${code}` as TranslationKey;
  return key in da ? t(key) : t("common.error");
}
